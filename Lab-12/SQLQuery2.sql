CREATE TABLE PUBLISTER(
	PUBLISTERID INT PRIMARY KEY,
	PUBLISTERNAME VARCHAR(50) NOT NULL UNIQUE,
	CITY VARCHAR(50) NOT NULL 
);

CREATE TABLE AUTHOR(
	AUTHORID INT PRIMARY KEY,
	AUTHORNAME VARCHAR(100) NOT NULL,
	CONTRY VARCHAR(50) NULL
);

CREATE TABLE BOOK(
	BOOKID INT PRIMARY KEY,
	TITLE VARCHAR(200) NOT NULL,
	AUTHORID INT FOREIGN KEY REFERENCES AUTHOR(AUTHORID) NOT NULL,
	PUBLISHERID INT FOREIGN KEY REFERENCES PUBLISTER(PUBLISTERID) NOT NULL,
	PRICE DECIMAL(8,2) NOT NULL,
	PUBLICATIONYEAR INT NOT NULL
);

