--2) CREATE A VIEW NAMED GOLDCUSTOMERSORDERS THAT DISPLAYS ALL ORDERS PLACED BY GOLD MEMBERS. 
CREATE VIEW GOLDCUTOMERSORDERS
AS
SELECT * 
FROM CUSTOMERS C
RIGHT JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
WHERE MEMBERSHIP = 'GOLD'

--3) CREATE A VIEW ELECTRONICORDERS DISPLAYING ONLY ELECTRONICS ORDERS. 
CREATE VIEW ELECTRONICORDERS
AS
SELECT *
FROM ORDERS O
JOIN CUSTOMERS C
ON C.CUSTOMERID = O.CUSTOMERID
WHERE CATEGORY = 'ELECTRONICS'

--4) CREATE A VIEW CUSTOMERPURCHASESUMMARY SHOWING THE TOTAL PURCHASE AMOUNT FOR EACH CUSTOMER. 
--(PURCHASE AMOUNT = QUANTITY * PRICE) 
CREATE VIEW CUSTOMERPURCHASESUMMARY
AS
SELECT CUSTOMERNAME,SUM(QUANTITY*PRICE)
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY CUSTOMERNAME

--5) CREATE A VIEW CUSTOMERORDERCOUNT SHOWING: 
--• CUSTOMER NAME 
--• NUMBER OF ORDERS PLACED 
CREATE VIEW CUSTOMERORDERCOUNT
AS
SELECT CUSTOMERNAME,COUNT(ORDERID) AS ORDERS_PLACED
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY CUSTOMERNAME

--6) CREATE A VIEW CATEGORYSALES DISPLAYING: 
--• CATEGORY 
--• NUMBER OF ORDERS 
--• TOTAL QUANTITY SOLD
CREATE VIEW CATEGORYSALES
AS
SELECT CATEGORY,COUNT(ORDERID),COUNT(QUANTITY)
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY CATEGORY

--7) CREATE A VIEW AMOUNTDETAILS DISPLAYING: 
--• MEMBERSHIP TYPE 
--• AVERAGE PURCHASE AMOUNT PER ORDER  
CREATE VIEW AMOUNTDETAILS
AS
SELECT MEMBERSHIP,AVG(PRICE*QUANTITY)
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY MEMBERSHIP

--8) CREATE A VIEW CITYSALES DISPLAYING: 
--• CITY 
--• TOTAL CUSTOMERS WHO PLACED ORDERS 
--• TOTAL PURCHASE AMOUNT
CREATE VIEW CITYSALES
AS
SELECT CITY,COUNT(CUSTOMERID),SUM(QUANTITY*PRICE)
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY CITY

--9) CREATE A VIEW CUSTOMERSALES DISPLAYING: 
--• CUSTOMER NAME 
--• MEMBERSHIP 
--• TOTAL QUANTITY PURCHASED 
--• TOTAL AMOUNT SPENT 
CREATE VIEW CUSTOMERSALES
AS
SELECT CUSTOMERNAME,MEMBERSHIP,COUNT(QUANTITY),SUM(QUANTITY*PRICE)
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY CUSTOMERNAME,MEMBERSHIP

--10) CREATE A VIEW CUSTOMERMEMBERSHIP DISPLAYING: 
--• CATEGORY 
--• MEMBERSHIP TYPE 
--• TOTAL SALES 
--• AVERAGE QUANTITY PURCHASEd 
CREATE VIEW CUSTOMERMEMBERSHIP
AS
SELECT CATEGORY,MEMBERSHIP,SUM(QUANTITY*PRICE),AVG(QUANTITY)
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID
GROUP BY CATEGORY,MEMBERSHIP