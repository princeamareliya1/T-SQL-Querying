--) CREATE A VIEW NAMED CUSTOMERORDERS DISPLAYING: 
--• CUSTOMER NAME 
--• CITY 
--• PRODUCT 
--• CATEGORY 
--• QUANTITY 
--• PRICE 

CREATE VIEW CUSTOMERORDERS
AS
SELECT CUSTOMERNAME,CITY,PRODUCT,CATEGORY,QUANTITY,PRICE
FROM CUSTOMERS C
JOIN ORDERS O
ON C.CUSTOMERID = O.CUSTOMERID

